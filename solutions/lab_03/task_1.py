students_data = [
    (95, "exam", 1),       # Отличный
    (85, "project", 4),    # Хороший -> Удовлетворительный (пропуски > 3)
    (60, "practice", 0),   # Удовлетворительный
    (59, "exam", 2),       # Недостаточный
    (100, "project", 5),   # Отличный -> Хороший (пропуски > 3)
    (0, "practice", 3),    # Недостаточный
    (74, "exam", 4),       # Удовлетворительный -> Недостаточный (пропуски > 3)
    (75, "project", 3),    # Хороший
    (89, "practice", 1),   # Хороший
    (90, "exam", 0),       # Отличный
    (105, "exam", 2),      # Ошибка: балл > 100
    (50, "project", 6),    # Ошибка: пропуски > 5
    (80, "unknown", 2)     # Неизвестный тип работы
]

total = {
    'отличный': 0,
    'хороший': 0,
    'удовлетворительный': 0,
    'недостаточный': 0
}

for stud in students_data:
    n, t, s = stud
    if not(0<=n<=100 and 0<=s<=5):
        print('error: incorrect value')
    else:
        if 90<=n<=100: level = 'отличный'
        elif 75<=n<=89: level = 'хороший'
        elif 60<=n<=74: level = 'удовлетворительный'
        else: level = 'недостаточный'

        if s>3:
            if level == 'отличный': level = 'хороший'
            elif level == 'хороший': level = 'удовлетворительный'
            else: level = 'недостаточный'

        match t:
            case 'exam': desc = 'экзаменационная работа'
            case 'project': desc = 'проектная работа'
            case 'practice': desc = 'практическая работа'
            case _: desc = 'неизвестный тип'
        print(f"Балл: {n:3} | Пропуски: {s} | Тип: {desc:<22} | Уровень: {level}")

        total[level] +=1
print()
print('=============Итоговая сводка=============')
for lvl, count in total.items():
    print(f"уровень {lvl:<25}: {count} чел.")


